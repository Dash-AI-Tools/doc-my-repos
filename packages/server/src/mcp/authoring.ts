const SEVERITY_ORDER = { error: 0, warning: 1, info: 2 } as const;

function describeFinding(f: Finding): string {
  const where = [
    f.key === undefined ? null : `key ${f.key}`,
    f.line === undefined ? null : `line ${f.line}`,
  ]
    .filter((part) => part !== null)
    .join(", ");
  const extra = [f.excerpt === undefined ? null : `"${f.excerpt}"`, f.suggestion ?? null]
    .filter((part) => part !== null)
    .join(" ");
  return `${f.severity} ${f.code}${where === "" ? "" : ` (${where})`}: ${f.message}${extra === "" ? "" : ` ${extra}`}`;
}

export const validateOkfDocumentTool = defineTool({
  name: "validate_okf_document",
  title: "Validate an OKF document",
  description:
    "Checks the Markdown of a draft document (at most 256 KB) against OKF and, when a repository " +
    "is named, against its conventions: links to documents that do not exist and types, tags or " +
    "statuses it does not use yet. Returns valid (true when there are no errors) and findings, " +
    "each with a fixed code, a severity, a message and a line. Nothing is stored or logged. Fix " +
    "every error and read every warning before the developer commits the file.",
  inputShape: {
    content: z.string().describe("The whole file: frontmatter and Markdown."),
    path: z
      .string()
      .max(1000)
      .optional()
      .describe("Where the file will be in the repository, for example docs/guides/setup.md."),
    repository: z
      .string()
      .max(200)
      .optional()
      .describe("The repository as owner/name, for its vocabulary and for link checking."),
  },
  run: async ({ content, path, repository }, ctx) => {
    if (Buffer.byteLength(content, "utf8") > MAX_CONTENT_BYTES) {
      return {
        structured: { error: "too_large", valid: false },
        text: "The content is larger than 256 KB, so nothing was validated.",
        isError: true,
      };
    }
    const resolved = await resolveRepository(ctx, repository);
    if ("error" in resolved) return resolved.error;
    const { repo } = resolved;

    let vocabulary: Vocabulary | undefined;
    let knownPaths: Set<string> | undefined;
    if (repo !== null) {
      const [facets, paths] = await Promise.all([
        getRepoFacets(ctx.db, { id: repo.id }),
        getDocPaths(ctx.db, { id: repo.id }),
      ]);
      vocabulary = {
        types: facets.types.map((f) => f.value),
        tags: facets.tags.map((f) => f.value),
        statuses: facets.statuses.map((f) => f.value),
      };
      knownPaths = paths;
    }
    const wanted = path?.trim().replace(/^\.?\/+/, "") ?? "";
    const result = validateOkfDocument(content, {
      ...(wanted === "" ? {} : { path: wanted }),
      ...(vocabulary === undefined ? {} : { vocabulary }),
      ...(knownPaths === undefined ? {} : { knownPaths }),
      ...(repo === null ? {} : { docsFolder: repo.docsPath }),
      now: ctx.now(),
    });
    const findings = [...result.findings].sort(
      (a, b) =>
        SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity] || (a.line ?? 0) - (b.line ?? 0),
    );
    const tally = (severity: Finding["severity"]) =>
      findings.filter((f) => f.severity === severity).length;
    const summary = { errors: tally("error"), warnings: tally("warning"), info: tally("info") };
    return {
      structured: {
        notice: UNTRUSTED_NOTICE,
        valid: result.valid,
        summary,
        findings,
        repository: repo === null ? null : `${repo.owner}/${repo.name}`,
      },
      text: [
        `${result.valid ? "Valid" : "Not valid"}: ${summary.errors} errors, ${summary.warnings} warnings, ${summary.info} notes.`,
        ...findings.map(describeFinding),
      ].join("\n"),
    };
  },
});

