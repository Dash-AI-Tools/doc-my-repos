export const getOkfGuidelines = defineTool({
  name: "get_okf_guidelines",
  title: "Get a repository's OKF guidelines",
  description:
    "Finds the repository's OKF guidelines: the file okf-guidelines.md in its docs folder (or its " +
    "guides folder). If there is one, returns it. If not, returns a generated draft built from " +
    "OKF and from the repository's own types, tags and statuses, with the path to save it at and " +
    "instructions: save it in the developer's checkout and let the developer review and commit " +
    "it. Without a repository, returns the generic draft. Call this before writing a document.",
  inputShape: {
    repository: z
      .string()
      .max(200)
      .optional()
      .describe("The repository as owner/name. Leave out for the generic draft."),
  },
  run: async ({ repository }, ctx) => {
    const resolved = await resolveRepository(ctx, repository);
    if ("error" in resolved) return resolved.error;
    const { repo } = resolved;

    if (repo !== null) {
      const guidelines = await findOkfGuidelines(ctx.db, { id: repo.id });
      if (guidelines !== null) {
        const content = block(guidelines.body, MAX_GUIDELINES_CHARACTERS);
        const page = docUrl(repo.owner, repo.name, guidelines.path, repo.docsPath);
        const structured = {
          notice: UNTRUSTED_NOTICE,
          found: true,
          repository: `${repo.owner}/${repo.name}`,
          path: guidelines.path,
          title: line(guidelines.title),
          content: content.text,
          contentTruncated: content.truncated,
          url: `${ctx.origin}${page ?? repoUrl(repo.owner, repo.name)}`,
        };
        return {
          structured,
          text: [
            UNTRUSTED_NOTICE,
            `The OKF guidelines of ${structured.repository} are in ${structured.path}. Follow them.`,
            structured.url,
            fenced(content.text),
          ].join("\n"),
        };
      }
    }

    let vocabulary: GuidelinesVocabulary = EMPTY_VOCABULARY;
    let layout: GuidelinesRepo | null = null;
    if (repo !== null) {
      const [facets, outline] = await Promise.all([
        getRepoFacets(ctx.db, { id: repo.id }),
        getRepoOutline(ctx.db, { id: repo.id }, LAYOUT_SAMPLE),
      ]);
      vocabulary = {
        types: counts(facets.types),
        tags: counts(facets.tags),
        statuses: counts(facets.statuses),
      };
      layout = {
        docsPath: repo.docsPath,
        isOkf: repo.isOkf,
        okfVersion: repo.okfVersion,
        folders: topFolders(
          outline.docs.map((d) => d.path),
          repo.docsPath,
        ),
      };
    }
    const draft = renderGuidelines(vocabulary, layout, ctx.now());
    const structured = {
      notice: UNTRUSTED_NOTICE,
      found: false,
      repository: repo === null ? null : `${repo.owner}/${repo.name}`,
      suggestedPath: draft.suggestedPath,
      draft: draft.markdown,
      instructions: draft.instructions,
    };
    return {
      structured,
      text: [
        repo === null
          ? "No repository was named, so this is the generic OKF guidelines draft."
          : `${structured.repository} has no okf-guidelines.md. Here is a draft built from OKF and from the vocabulary its documents already use.`,
        draft.instructions,
        "The draft file follows.",
        draft.markdown,
      ].join("\n\n"),
    };
  },
});

