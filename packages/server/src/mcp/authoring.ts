/**
 * The OKF authoring tools and prompt (mcp-agent-access spec `okf-authoring`): `get_okf_guidelines`,
 * `validate_okf_document` and the `write-okf-doc` prompt. Agents write documents in the developer's
 * own checkout; nothing here writes anywhere. The guidelines come from the repository's own
 * `okf-guidelines.md` when it has one, else from a draft generated by `renderGuidelines` (pure, no
 * model). Validation is `validateOkfDocument`, which uses the sync's own parser and rules and
 * stores and logs nothing it is given.
 */

const NOT_FOUND_REPOSITORY =
  "Repository not found. Use owner/name as returned by list_repositories.";
const BAD_REPOSITORY = "The repository must be written owner/name.";
const MAX_GUIDELINES_CHARACTERS = 100_000;
const MAX_FOLDERS = 30;
/** Documents read to describe the folder layout, by path. */
const LAYOUT_SAMPLE = 1000;

const failure = (code: "not_found" | "invalid_argument", text: string): ToolOutput => ({
  structured: { error: code },
  text,
  isError: true,
});

type Resolved = {
  id: number;
  owner: string;
  name: string;
  docsPath: string | null;
  isOkf: boolean;
  okfVersion: string | null;
};

async function resolveRepository(
  ctx: ToolContext,
  repository: string | undefined,
): Promise<{ repo: Resolved | null } | { error: ToolOutput }> {
  if (repository === undefined || repository.trim() === "") return { repo: null };
  const ref = parseRepository(repository);
  if (ref === null) return { error: failure("invalid_argument", BAD_REPOSITORY) };
  const found = await getRepo(ctx.db, ref.owner, ref.name);
  if (found === null) return { error: failure("not_found", NOT_FOUND_REPOSITORY) };
  return {
    repo: {
      id: found.id,
      owner: found.owner,
      name: found.name,
      docsPath: found.docsPath,
      isOkf: found.isOkf,
      okfVersion: found.okfVersion,
    },
  };
}

const counts = (items: readonly FacetCount[]) =>
  items.map((f) => ({ value: f.value, count: f.count }));

/** The top-level folders of the docs folder, from the first documents by path. */
function topFolders(paths: readonly string[], docsPath: string | null): string[] {
  const prefix = docsPath === null ? "" : `${docsPath.replace(/\/+$/, "")}/`;
  const folders = new Set<string>();
  for (const path of paths) {
    if (prefix !== "" && !path.startsWith(prefix)) continue;
    const rest = path.slice(prefix.length);
    const slash = rest.indexOf("/");
    if (slash > 0) folders.add(rest.slice(0, slash));
  }
  return [...folders].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)).slice(0, MAX_FOLDERS);
}

