// Embeds docs/github-app-manifest.json (the single source) into the package as a TypeScript module,
// so the compiled installer carries it. Run by `pnpm build`; the output is committed, and a test
// fails when it differs from the source.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../../../docs/github-app-manifest.json", import.meta.url));
const target = fileURLToPath(new URL("../src/manifest-template.generated.ts", import.meta.url));

const text = readFileSync(source, "utf8");
JSON.parse(text);
if (text.includes("`") || text.includes("${") || text.includes("\\")) {
  throw new Error("The manifest contains characters the embedder does not support.");
}

writeFileSync(
  target,
  [
    "// Generated by scripts/embed-manifest.mjs from docs/github-app-manifest.json. Do not edit.",
    `export const MANIFEST_TEMPLATE_JSON = \`${text}\`;`,
    "",
  ].join("\n"),
);
